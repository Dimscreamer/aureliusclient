/**
 * Основной обработчик для Module Flex.
 * Аргументы: input объект + sessionState (не используются напрямую здесь,
 * обработка идёт через executeSingleModule в Core_Engine).
 * Эта функция — точка входа для ручного вызова.
 */
function handleFlexModule(aresResponse) {
  // Flex не выполняет протоколы и не имеет тегов для парсинга.
  // Просто возвращает ответ как есть, предварительно очищая любые случайные теги.
  if (typeof aresResponse !== 'string') return aresResponse;

  // Защита: убираем любые случайно попавшие теги анализа или задач
  aresResponse = aresResponse.replace(/\[\[ADD_TASK[\s\S]*?\]\]/gi, "");
  aresResponse = aresResponse.replace(/\[\[METANOIA_LOG[\s\S]*?\]\]/gi, "");
  aresResponse = aresResponse.replace(/\[\[DELETE_TASK[\s\S]*?\]\]/gi, "");
  aresResponse = aresResponse.replace(/\[\[TG_REMINDER[\s\S]*?\]\]/gi, "");

  return aresResponse.trim();
}

// ==============================================================================
// 🔧 КОНТЕКСТ (передаётся в askAres)
// ==============================================================================

/**
 * Контекст для Flex Module — минимальный.
 * Flex не читает дневник, не читает задачи, не читает метаноя-лог.
 * Только время суток, чтобы адаптировать практику.
 */
function getMetanoiaFlexContext(userText, history) {
  const now  = new Date();
  const hour = now.getHours();
  let timeOfDay = "дневное";
  if (hour < 9)  timeOfDay = "утреннее";
  if (hour >= 20) timeOfDay = "вечернее";
  if (hour >= 23 || hour < 5) timeOfDay = "ночное";

  return `\n\n[FLEX CONTEXT]: Время суток — ${timeOfDay}. Адаптируй практику под это время. Утром — активации и намерения, вечером — расслабление и наблюдение.

[FLEX STRICT MODE]: Ты в режиме практики. ЗАПРЕЩЕНО: анализ, задачи, теги [[METANOIA_LOG]], [[ADD_TASK]]. ТОЛЬКО одна конкретная практика.`;
}

// ==============================================================================
// 💬 ПРОМПТ МОДУЛЯ (перенесён из Prompt.js в v10.0)
// ==============================================================================
function getFlexIntent() {
  return `MODE: FLEX MODULE (медитации и практики)
Ты сейчас в режиме коротких практик и упражнений.`;
}

function getFlexProtocols() {
  return `РОЛЬ: дать конкретную практику для выполнения прямо сейчас.

ЧТО ДЕЛАТЬ:
— Предложи 1 конкретную практику: дыхательное упражнение, наблюдение мысли, пауза, телесный скан
— Дай 3–5 простых шагов для выполнения
— Практика должна длиться 5–15 минут
— Стиль: спокойный, чёткий, без лишних слов

АБСОЛЮТНЫЕ ЗАПРЕТЫ:
— ЗАПРЕЩЕНО анализировать жизнь, поведение, триггеры
— ЗАПРЕЩЕНО делать когнитивный разбор или психологические выводы
— ЗАПРЕЩЕНО писать [[METANOIA_LOG:...]] или любые теги анализа
— ЗАПРЕЩЕНО создавать задачи [[ADD_TASK:...]]
— ЗАПРЕЩЕНО задавать вопросы о причинах состояния

Если пользователь хочет разбор — просто спроси: "Хочешь разбор ситуации?"`;
}

