// 🧩 GLOBAL PROTOCOL INDEX GENERATOR
// ==============================================================================
function getGlobalProtocolIndex() {
  if (typeof getModuleRegistry !== 'function') return "";
  var reg = getModuleRegistry();
  var idx = "\n\n[GLOBAL PROTOCOL INDEX (ДОСТУПНЫЕ ФУНКЦИИ СИСТЕМЫ)]\nЕсли запрос пользователя явно относится к одной из этих функций, ты ДОЛЖЕН использовать соответствующий тег, чтобы передать управление нужному модулю. ВЫДУМЫВАТЬ СВОИ ТЕГИ (КОТОРЫХ НЕТ В СПИСКЕ) — КАТЕГОРИЧЕСКИ ЗАПРЕЩЕНО!\n";
  for (var k in reg) {
    if (k === 'base' || !reg[k].enabled) continue;
    var m = reg[k];
    if (m.protocols && m.protocols.length > 0) {
      for (var p = 0; p < m.protocols.length; p++) {
        if (m.protocols[p].desc) {
          idx += "— " + m.protocols[p].desc + "\n";
        }
      }
    }
  }
  idx += "\nВАЖНО: ИГНОРИРУЙ любые теги из истории чата, если их нет в этом списке (например, если ранее была допущена ошибка типа ADD_NUTRITION, забудь про нее). Используй СТРОГО те форматы, которые описаны здесь. Если для заполнения тега тебе нужно произвести расчеты (например, КБЖУ) — сделай это самостоятельно (примерно), опираясь на свою базу знаний, но ОБЯЗАТЕЛЬНО используй правильный тег!\n";
  return idx;
}

