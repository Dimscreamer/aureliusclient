/**
 * Единая система форматирования сообщений ARES.
 * 
 * @param {string} title - Заголовок (например, "АНАЛИЗ ПАТТЕРНОВ")
 * @param {string} icon - Эмодзи (например, "📊", может быть пустым)
 * @param {string} body - Тело сообщения (уже отформатированное HTML)
 * @param {string} footer - (Опционально) Текст для подвала курсивом
 * @returns {string} Готовое сообщение для отправки в Telegram
 */
function aresFormatMessage(title, icon, body, footer) {
  var msg = "";
  
  // 1. Формирование заголовка
  if (title) {
    var prefix = icon ? icon + " " : "";
    // Делаем заголовок жирным и в верхнем регистре, без линий-разделителей
    msg += prefix + "<b>" + title.toUpperCase() + "</b>\n\n";
  }
  
  // 2. Обработка тела сообщения (санитизация теперь происходит глобально в 6_Telegram.js)
  if (body) {
    msg += body.trim() + "\n\n";
  }
  
  
  // 3. Формирование подвала
  if (footer) {
    msg += "<i>" + footer + "</i>";
  }
  
  return msg.trim();
}
